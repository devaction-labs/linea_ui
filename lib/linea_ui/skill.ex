defmodule LineaUI.Skill do
  @moduledoc """
  Builds the Claude Code skill that teaches an agent to write LineaUI markup.

  Everything comes from the compiled components (`__components__/0` and their docs), so the
  skill describes exactly the installed version: `SKILL.md` is a short index with the rules
  that hold for every component, and `references/<component>.md` holds the attrs, slots and
  examples of one component, read only when that component is used.

  `mix linea_ui.install` writes it when it sets the app up and `mix linea_ui.gen.skill` refreshes
  it after an upgrade.
  """

  @marker "<!-- linea_ui -->"
  @pointer """
  #{@marker}
  ## UI

  UI is LineaUI. Load `.claude/skills/linea-ui/SKILL.md` before writing or changing HEEx, and read
  the component's reference before using it. Regenerate it with `mix linea_ui.install` after upgrading.
  """

  @doc "The comment that marks the pointer block in `AGENTS.md` and `CLAUDE.md`."
  @spec marker() :: String.t()
  def marker, do: @marker

  @doc "The block `AGENTS.md` and `CLAUDE.md` carry to send an agent to the skill."
  @spec pointer() :: String.t()
  def pointer, do: @pointer

  @doc "The version of the installed package, which the generated `SKILL.md` carries in its heading."
  @spec version() :: String.t()
  def version do
    Application.load(:linea_ui)
    :linea_ui |> Application.spec(:vsn) |> to_string()
  end

  @doc "The version a skill directory was generated for, or `nil` when it has no `SKILL.md`."
  @spec installed_version(Path.t()) :: String.t() | nil
  def installed_version(path) do
    with {:ok, contents} <- File.read(Path.join(path, "SKILL.md")),
         [_, version] <- Regex.run(~r/^# LineaUI (\S+)$/m, contents) do
      version
    else
      _ -> nil
    end
  end

  @doc "Writes the skill under `path`, replacing the references of a previous run."
  @spec write!(Path.t()) :: [{String.t(), String.t()}]
  def write!(path) do
    File.rm_rf!(Path.join(path, "references"))
    files = files()

    Enum.each(files, fn {relative, contents} ->
      file = Path.join(path, relative)
      File.mkdir_p!(Path.dirname(file))
      File.write!(file, contents)
    end)

    files
  end

  @doc "The files of the skill, as `{relative_path, contents}`."
  @spec files() :: [{String.t(), String.t()}]
  def files do
    version = version()
    documented = LineaUI.Docs.components()

    [{"SKILL.md", index(documented, version)} | Enum.map(documented, &reference/1)]
  end

  defp index(components, version) do
    rows =
      Enum.map_join(components, "\n", fn c ->
        tags = Enum.map_join(c.functions, " ", &"`<.#{&1.name}>`")
        "| #{tags} | #{c.summary} | [#{c.key}.md](references/#{c.key}.md) |"
      end)

    """
    ---
    name: linea-ui
    description: >-
      LineaUI #{version} — the Phoenix LiveView component kit with the LineOne design
      (buttons, forms, select, pickers, modal, drawer, dropdown, tables, tabs, app shell,
      toasts and more). Use when writing or editing HEEx/LiveView markup in this app, or a
      LiveView test that asserts on rendered UI. Read references/<component>.md before using
      a component: attrs and their allowed values are fixed, guessing them renders wrong markup.
    ---

    # LineaUI #{version}

    Generated by `mix linea_ui.gen.skill` from the installed package; run it again after
    upgrading. When this file and `deps/linea_ui/lib` disagree, the source wins.

    ## Rules

    - Components are imported by `use LineaUI` (often in `html_helpers/0`). Never hand-write
      LineOne markup or Tailwind for something a component covers; pass `class` to adjust: it is
      merged last and replaces conflicting defaults (`class="rounded-full px-8"`).
    - Colors are LineOne's: `neutral primary secondary accent info success warning error`, each
      component accepts the subset listed in its reference. Never hardcode a color class for a
      themed thing; dark mode is the `dark` class on `<html>` and every component handles it.
    - Form controls take `field={@form[:name]}` (id, name, value and errors come from it) inside
      `<.form for={@form} phx-change="validate" phx-submit="save">`. Custom controls (select,
      pickers, tags, editor) submit through hidden inputs, so `phx-change` sees them like native ones.
    - Overlays (modal, drawer, popover, dropdown, tooltip) need a stable `id`:
      `phx-click={LineaUI.open("id")}`, `LineaUI.close(socket, "id")` in `handle_event/3`,
      `LineaUI.toggle(%JS{}, "id")` in a pipeline. `on_close`/`on_open` report back to the server.
    - Events a component emits go to the LiveView, or to a LiveComponent with `target={@myself}`.
      Lists (table, data_table, timeline...) accept `@streams.x` with `row_id`.
    - Every component forwards unknown attributes (`id`, `phx-*`, `data-*`, `aria-*`) to its root.
    - Icons: components draw their small glyphs (chevrons, close, check, arrows...) as LineOne's
      SVGs, or as Hugeicons when the app sets `config :linea_ui, :icons, :hugeicons` (with the
      `hugeicons.cjs` Tailwind plugin in app.css, see the README). For your own icons write
      `<.icon name="huge-search-01" class="size-5" />`: the `huge-*` name in full, never
      interpolated, and only names of the free Stroke Rounded set (an unknown name renders nothing).

    ## Components

    | Tags | What | Reference |
    |---|---|---|
    #{rows}
    """
  end

  defp reference(component) do
    body = Enum.map_join(component.functions, "\n\n", &function_section/1)

    {"references/#{component.key}.md",
     """
     # #{inspect(component.module)}

     #{component.moduledoc}

     #{body}
     """}
  end

  defp function_section(function) do
    """
    ## `<.#{function.name}>`

    #{function.doc}

    #{attrs_table(function.attrs)}
    #{global(function.global)}

    #{slots_list(function.slots)}
    """
    |> String.replace(~r/\n{3,}/, "\n\n")
    |> String.trim()
  end

  defp attrs_table([]), do: ""

  defp attrs_table(attrs) do
    rows = Enum.map_join(attrs, "\n", &attr_row/1)

    """
    | Attr | Type | Default | Values / notes |
    |---|---|---|---|
    #{rows}
    """
  end

  defp attr_row(attr) do
    "| `#{attr.name}`#{required(attr)} | #{type(attr.type)} | #{default(attr.opts)} | #{notes(attr)} |"
  end

  defp required(%{required: true}), do: " (required)"
  defp required(_attr), do: ""

  defp type(type), do: "`#{inspect(type)}`"

  defp default(opts) do
    case Keyword.fetch(opts, :default) do
      {:ok, value} -> "`#{inspect(value)}`"
      :error -> ""
    end
  end

  defp notes(attr) do
    [values(attr.opts), attr.doc]
    |> Enum.reject(&(&1 in [nil, ""]))
    |> Enum.join(" — ")
    |> String.replace("\n", " ")
    |> String.replace("|", "\\|")
  end

  defp values(opts) do
    case Keyword.fetch(opts, :values) do
      {:ok, values} -> Enum.map_join(values, ", ", &"`#{&1}`")
      :error -> nil
    end
  end

  defp global(nil), do: ""

  defp global(attr) do
    included =
      attr.opts
      |> Keyword.get(:include, [])
      |> Enum.map_join(", ", &"`#{&1}`")

    "Any other HTML/phx attribute goes to the root element#{extra(included)}."
  end

  defp extra(""), do: ""
  defp extra(included), do: ", including #{included}"

  defp slots_list([]), do: ""

  defp slots_list(slots) do
    items = Enum.map_join(slots, "\n", &slot_item/1)
    "Slots:\n\n" <> items
  end

  defp slot_item(slot) do
    attrs = Enum.map_join(slot.attrs, ", ", &"`#{&1.name}`")

    ["- `<:#{slot.name}>`", required(slot), slot_attrs(attrs), slot_doc(slot.doc)]
    |> Enum.join()
  end

  defp slot_attrs(""), do: ""
  defp slot_attrs(attrs), do: " — attrs: " <> attrs

  defp slot_doc(nil), do: ""
  defp slot_doc(doc), do: " — " <> String.replace(doc, "\n", " ")
end
