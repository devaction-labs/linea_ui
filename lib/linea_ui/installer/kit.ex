if Code.ensure_loaded?(Igniter) do
  defmodule LineaUI.Installer.Kit do
    @moduledoc """
    The step of `mix linea_ui.install --kit`: the app shell with a menu, ready to edit.

    It creates `lib/<app>_web/nav.ex` (`<App>Web.Nav.items/1`, the menu as data) and
    `lib/<app>_web/components/layouts/shell.ex` (`<App>Web.Layouts.Shell.app_shell/1`, which renders
    `LineaUI.Components.Shell.shell/1`), and sets `config :linea_ui, :shell` to read the menu.

    The layout goes in a new module instead of an edit of `Layouts`: creating a file is idempotent by
    its existence (a second run, or an app that already has the file, is left alone), while injecting
    a function into the generated `Layouts` would depend on its shape. Call it from `Layouts.app/1`
    or from your own layout.
    """

    alias Igniter.Libs.Phoenix, as: PhoenixApp
    alias Igniter.Project.Module

    @doc "Creates the menu and the shell layout, sets the config and explains the next steps."
    @spec install(Igniter.t()) :: Igniter.t()
    def install(igniter) do
      web = PhoenixApp.web_module(igniter)
      nav = Module.parse("#{inspect(web)}.Nav")
      shell = Module.parse("#{inspect(web)}.Layouts.Shell")

      igniter
      |> create(nav, nav_source(web), "lib/#{path(web)}/nav.ex")
      |> create(shell, shell_source(shell), "lib/#{path(web)}/components/layouts/shell.ex")
      |> Igniter.Project.Config.configure("config.exs", :linea_ui, [:shell, :sidebar], :sections)
      |> Igniter.Project.Config.configure(
        "config.exs",
        :linea_ui,
        [:shell, :nav],
        {:code, Sourceror.parse_string!("{#{inspect(nav)}, :items}")}
      )
      |> Igniter.add_notice(notice(nav, shell, web))
    end

    defp path(web), do: web |> inspect() |> Macro.underscore()

    defp create(igniter, module, body, file) do
      {exists?, igniter} = Module.module_exists(igniter, module)

      case exists? or Igniter.exists?(igniter, file) do
        true ->
          Igniter.add_warning(igniter, "LineaUI --kit: #{file} already exists, left as it is.")

        false ->
          Igniter.create_new_file(igniter, file, body)
      end
    end

    defp nav_source(web) do
      """
      defmodule #{inspect(web)}.Nav do
        @moduledoc \"\"\"
        The menu of the app shell, as data. Generated by `mix linea_ui.install --kit` and read by
        `LineaUI.Components.Shell.shell/1` through `config :linea_ui, :shell, nav: {#{inspect(web)}.Nav, :items}`.

        `items/1` receives the assigns of the shell and returns a list of maps. The same list feeds
        every sidebar format (`:sections`, `:rail`, `:tree`).

        An item has:

        * `label` - the text
        * `icon` - the icon name
        * `navigate`, `href` or `patch` - where it goes
        * `count` - a number shown beside the label
        * `color` - the color of its icon
        * `badge` - a short text shown beside the label
        * `children` - the items nested under it

        A group has:

        * `group` - the title of the section
        * `icon` - its icon
        * `collapsible` - whether it folds
        * `items` - its items
        \"\"\"

        # The paths are plain strings so a fresh app compiles without warnings. Once the routes
        # exist in your router, `~p"/pedidos"` (with `use #{inspect(web)}, :verified_routes`) works too.
        def items(assigns) do
          [
            %{label: "Início", icon: "home", navigate: "/"},
            %{label: "Assistente", icon: "spark", navigate: "/assistente"},
            %{
              group: "Vendas",
              icon: "cart",
              items: [
                %{
                  label: "Pedidos",
                  icon: "cart",
                  navigate: "/pedidos",
                  count: assigns[:abertos],
                  children: [
                    %{
                      label: "Abertos",
                      icon: "doc",
                      color: "blue",
                      navigate: "/pedidos?status=aberto"
                    }
                  ]
                }
              ]
            }
          ]
        end
      end
      """
    end

    defp shell_source(shell) do
      """
      defmodule #{inspect(shell)} do
        @moduledoc \"\"\"
        The app layout with LineaUI's Shell. Generated by `mix linea_ui.install --kit`. The sidebar
        format and the menu come from `config :linea_ui, :shell`.
        \"\"\"
        use Phoenix.Component

        attr :current_path, :string, default: nil
        attr :current_user, :map, default: nil
        slot :inner_block

        def app_shell(assigns) do
          ~H\"\"\"
          <LineaUI.Components.Shell.shell current={@current_path} user={@current_user}>
            {render_slot(@inner_block)}
          </LineaUI.Components.Shell.shell>
          \"\"\"
        end
      end
      """
    end

    defp notice(nav, shell, web) do
      """
      LineaUI --kit created:

        * lib/#{path(web)}/nav.ex - the menu (#{inspect(nav)}.items/1), edit it to match your routes
        * lib/#{path(web)}/components/layouts/shell.ex - #{inspect(shell)}.app_shell/1, which renders the Shell
        * config/config.exs - `config :linea_ui, :shell, sidebar: :sections, nav: {#{inspect(nav)}, :items}`

      Use it in your layout: `<#{inspect(shell)}.app_shell current_path={@current_path} current_user={@current_user}>`.

      The foot of the menu is a choice, `footer: :user | :version | :none` (the user card, the version of the
      system with its build and a "What's new" link, or nothing when the topbar has the avatar), with
      `version: "v1.4.2"` (or a map `%{version, build, navigate, label}`). Or per screen,
      `<.shell footer="version" version={...}>`.

      The menu format changes with `sidebar: :rail` or `sidebar: :tree` in the config, or per screen with
      `<.shell sidebar="tree">`. The items do not change. `<.sidebar>` is available to render the menu
      outside the Shell.

      Feed `current_path` from an `on_mount` hook of your `live_session` (#{inspect(web)}):

          def on_mount(:current_path, _params, _session, socket) do
            {:cont,
             Phoenix.LiveView.attach_hook(socket, :current_path, :handle_params, fn _params, url, socket ->
               {:cont, Phoenix.Component.assign(socket, :current_path, URI.parse(url).path)}
             end)}
          end
      """
    end
  end
end
